-- V001 — telemetry schema (metrics, events, rollups)
--
-- THIS FILE IS THE SOURCE OF TRUTH FOR THE TELEMETRY SCHEMA.
-- docs/design/architecture.md §8 describes intent; where the two differ, THIS WINS.
-- Rationale: three consecutive review rounds produced defects in a primary key that
-- prose could not catch. A migration either creates or it does not.
--
-- Requires PostgreSQL >= 14 (DETACH PARTITION ... CONCURRENTLY). Verified on 16.
-- Decisions: SM-D8, SM-D23, SM-D26. Constraint tests: backend/src/test/sql/V001_constraints_test.sql

CREATE SCHEMA IF NOT EXISTS sm_data;
SET search_path TO sm_data;

-- ---------------------------------------------------------------------------
-- PLACEMENT — immutable. Identity-bearing.
-- Split from binding policy per round-5 review: a binding also carried mutable
-- policy (restart_strategy, lifecycle_owner, ...). Making the whole record
-- immutable would mint a new identity on a UI toggle and end every graph.
-- ---------------------------------------------------------------------------
CREATE TABLE placement (
    tenant_id     uuid        NOT NULL,
    placement_id  uuid        NOT NULL,
    instance_id   uuid        NOT NULL,
    target_id     uuid        NOT NULL,   -- opaque; CP owns the Target row (no cross-schema FK)
    created_at    timestamptz NOT NULL DEFAULT now(),
    retired_at    timestamptz,            -- set on re-target; row is never mutated otherwise
    CONSTRAINT placement_pk PRIMARY KEY (tenant_id, placement_id),
    CONSTRAINT placement_unique_live UNIQUE (tenant_id, instance_id, target_id, created_at)
);

-- ---------------------------------------------------------------------------
-- BINDING POLICY — mutable, versioned. NOT part of telemetry identity.
-- ---------------------------------------------------------------------------
CREATE TABLE binding_policy (
    tenant_id              uuid        NOT NULL,
    placement_id           uuid        NOT NULL,
    policy_version         int         NOT NULL,
    infra_telemetry_source text        NOT NULL,
    config_mechanism       text        NOT NULL,
    lifecycle_owner        text        NOT NULL,
    restart_strategy       text        NOT NULL,
    selectors_jsonb        jsonb,
    valid_from             timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT binding_policy_pk PRIMARY KEY (tenant_id, placement_id, policy_version),
    CONSTRAINT binding_policy_placement_fk
        FOREIGN KEY (tenant_id, placement_id) REFERENCES placement (tenant_id, placement_id),
    CONSTRAINT binding_policy_source_ck
        CHECK (infra_telemetry_source IN ('direct-poll','local-collector','broker','federated')),
    CONSTRAINT binding_policy_lifecycle_ck CHECK (lifecycle_owner IN ('sm','customer'))
);

-- ---------------------------------------------------------------------------
-- SERIES — the dimension. Identity = tenant + instance + PLACEMENT + metric + source + labels.
-- placement_id (not policy) is what prevents multi-site merge: `cache-0` exists in
-- every cluster, so source_key alone is not globally unique.
-- ---------------------------------------------------------------------------
CREATE TABLE series (
    tenant_id           uuid   NOT NULL,
    series_id           bigint GENERATED BY DEFAULT AS IDENTITY,
    instance_id         uuid   NOT NULL,
    placement_id        uuid   NOT NULL,
    solution            text   NOT NULL,
    metric_name         text   NOT NULL,
    metric_type         text   NOT NULL,
    unit                text   NOT NULL,
    package_version     text   NOT NULL,   -- retyping gauge->counter across versions => new series
    source_key          text   NOT NULL,   -- STABLE replica identity; ephemeral incarnation goes in labels
    labels_jsonb        jsonb  NOT NULL DEFAULT '{}'::jsonb,
    labels_fingerprint  text   NOT NULL,
    CONSTRAINT series_pk PRIMARY KEY (tenant_id, series_id),
    CONSTRAINT series_placement_fk
        FOREIGN KEY (tenant_id, placement_id) REFERENCES placement (tenant_id, placement_id),
    CONSTRAINT series_identity_unique UNIQUE
        (tenant_id, instance_id, placement_id, metric_name, package_version,
         source_key, labels_fingerprint),
    CONSTRAINT series_metric_type_ck CHECK (metric_type IN ('counter','gauge','histogram'))
);

-- ---------------------------------------------------------------------------
-- METRICS_RAW — RANGE partitioned on ts. PK must include the partition key.
-- ---------------------------------------------------------------------------
CREATE TABLE metrics_raw (
    tenant_id     uuid             NOT NULL,
    series_id     bigint           NOT NULL,
    ts            timestamptz      NOT NULL,
    value_numeric double precision,
    CONSTRAINT metrics_raw_pk PRIMARY KEY (tenant_id, series_id, ts),
    CONSTRAINT metrics_raw_series_fk
        FOREIGN KEY (tenant_id, series_id) REFERENCES series (tenant_id, series_id)
) PARTITION BY RANGE (ts);

-- NO DEFAULT PARTITION: it makes DETACH PARTITION ... CONCURRENTLY illegal.
-- Partitions are pre-created N months ahead; out-of-range inserts MUST fail loudly.
CREATE TABLE metrics_raw_2026_08 PARTITION OF metrics_raw
    FOR VALUES FROM ('2026-08-01') TO ('2026-09-01');
CREATE TABLE metrics_raw_2026_09 PARTITION OF metrics_raw
    FOR VALUES FROM ('2026-09-01') TO ('2026-10-01');

CREATE INDEX metrics_raw_ts_idx ON metrics_raw (ts);

-- ---------------------------------------------------------------------------
-- ROLLUPS — same identity as raw, partitioned so retention is a partition drop.
-- ---------------------------------------------------------------------------
CREATE TABLE metrics_rollup_1h (
    tenant_id    uuid        NOT NULL,
    series_id    bigint      NOT NULL,
    bucket_start timestamptz NOT NULL,
    sample_count int         NOT NULL,
    expected_count int       NOT NULL,     -- for gap rendering
    sum_val      double precision,
    min_val      double precision,
    max_val      double precision,
    first_val    double precision,
    last_val     double precision,
    first_ts     timestamptz,
    last_ts      timestamptz,
    delta        double precision,          -- materialized for counters
    reset_count  int         NOT NULL DEFAULT 0,
    CONSTRAINT rollup_1h_pk PRIMARY KEY (tenant_id, series_id, bucket_start),
    CONSTRAINT rollup_1h_series_fk
        FOREIGN KEY (tenant_id, series_id) REFERENCES series (tenant_id, series_id)
) PARTITION BY RANGE (bucket_start);

CREATE TABLE metrics_rollup_1h_2026_08 PARTITION OF metrics_rollup_1h
    FOR VALUES FROM ('2026-08-01') TO ('2026-09-01');

-- ---------------------------------------------------------------------------
-- EVENTS_RAW — separate from metrics. Business events can share a timestamp.
-- source_namespace is the COLLISION DOMAIN (broker + replication group), NOT the
-- endpoint: per-endpoint namespacing would let one fanned-out event be stored twice
-- and double-count run totals.
-- ---------------------------------------------------------------------------
CREATE TABLE events_raw (
    tenant_id        uuid        NOT NULL,
    instance_id      uuid        NOT NULL,
    placement_id     uuid        NOT NULL,
    source_namespace text        NOT NULL,
    source_event_id  text        NOT NULL,
    event_type       text        NOT NULL,
    ts               timestamptz NOT NULL,
    payload_jsonb    jsonb,
    CONSTRAINT events_raw_pk PRIMARY KEY (tenant_id, ts, source_namespace, source_event_id),
    CONSTRAINT events_raw_placement_fk
        FOREIGN KEY (tenant_id, placement_id) REFERENCES placement (tenant_id, placement_id)
) PARTITION BY RANGE (ts);

CREATE TABLE events_raw_2026_08 PARTITION OF events_raw
    FOR VALUES FROM ('2026-08-01') TO ('2026-09-01');

CREATE INDEX events_raw_instance_idx ON events_raw (tenant_id, instance_id, ts);
