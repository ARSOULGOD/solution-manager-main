package com.solace.sm.launcher;

import com.solace.sm.launcher.AgentTestSupport.Result;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.PosixFilePermissions;
import java.time.Duration;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

/**
 * The shipped stack, as a test fixture (plan 015 T4.4): the launcher IMAGE that {@code runtime/scripts/build-image.sh} builds, PostgreSQL
 * 14 in a container on a private network, Phase 0 and Phase 1 run from the shipped files as their own one-shot containers, and the
 * application started from the documented environment. Used by the packaging drills and by the capacity run, so the thing measured is the
 * thing that ships.
 *
 * <p>Secrets follow the runtime contract (OR-138, I6): the five database passwords are generated by the shipped
 * {@code runtime/scripts/init-secrets.sh} into a secrets directory and reach the containers as READ-ONLY FILES ({@code *_PASSWORD_FILE});
 * the gateway key, the trust bundle, the CA keystore and its password are files under {@code /run/secrets/} too. No password is an
 * environment value, so {@code docker inspect} shows none. (The files are made group/world-readable inside a scratch directory so that
 * the image's uid 10001 can read them through Docker Desktop's file sharing; they are throwaway test material.)
 */
final class ContainerStack implements AutoCloseable {
    static final String MANAGEMENT_TOKEN = "management-token-" + UUID.randomUUID();
    static final String BOOTSTRAP_SECRET = "bootstrap-secret";

    /** Optional cgroup limits for a container, so a measurement names the hardware it was taken on. */
    record Limits(String cpus, String memory) {
        static final Limits NONE = new Limits(null, null);
    }

    /** One per stack: a recreated container must unwrap what the first one stored. */
    private final String masterKey = java.util.Base64.getEncoder().encodeToString(
            java.security.MessageDigest.getInstance("SHA-256").digest(UUID.randomUUID().toString().getBytes(java.nio.charset.StandardCharsets.UTF_8)));
    final String suffix = UUID.randomUUID().toString().substring(0, 8);
    final String network = "sm-it-net-" + suffix;
    final String db = "sm-it-db-" + suffix;
    final String image;
    final Path repo;
    final Path work;
    final Path certs;
    final Path secrets;
    final AgentGatewayTestPki pki;
    /** The address the host's connections arrive from inside the stack's network: what compose calls SM_TRUSTED_PROXY for a proxy on the host. */
    String networkGateway;
    int dbHostPort;
    JdbcTemplate sql;
    String jdbcUrl;
    private final boolean ownsImage;

    private ContainerStack(Path repo, Path work, String image, boolean ownsImage) throws Exception {
        this.repo = repo;
        this.work = work;
        this.image = image;
        this.ownsImage = ownsImage;
        this.certs = Files.createDirectories(work.resolve("certs"));
        this.secrets = work.resolve("secrets");
        this.pki = new AgentGatewayTestPki(certs, true);
        Files.writeString(certs.resolve("agent-ca.password"), AgentGatewayTestPki.PASSWORD);
        makeReadable(certs);
    }

    /** Builds the image from the repackaged jar already in {@code backend/launcher/target} and creates the fixture directories. */
    static ContainerStack create(boolean buildImage, String existingImage) throws Exception {
        Path repo = Path.of("..", "..").toAbsolutePath().normalize();
        Path work = Files.createTempDirectory(Path.of(System.getProperty("user.home")), "sm-it-pkg-");
        String tag = existingImage != null ? existingImage : "sm-launcher:it-" + UUID.randomUUID().toString().substring(0, 8);
        ContainerStack stack = new ContainerStack(repo, work, tag, existingImage == null);
        Result generated = AgentTestSupport.run(List.of("sh", "runtime/scripts/init-secrets.sh", "--dir", stack.secrets.toString()), repo,
                Duration.ofSeconds(60));
        if (!generated.ok()) {
            throw new IllegalStateException("init-secrets.sh failed: " + generated.output());
        }
        makeReadable(stack.secrets);
        if (buildImage && existingImage == null) {
            Result built = AgentTestSupport.run(List.of("bash", "-c", "SM_SKIP_MVN=1 ./runtime/scripts/build-image.sh " + tag), repo,
                    Duration.ofMinutes(10));
            if (!built.ok()) {
                throw new IllegalStateException("image build failed: " + built.output());
            }
        }
        return stack;
    }

    private static void makeReadable(Path directory) throws IOException {
        Files.setPosixFilePermissions(directory, PosixFilePermissions.fromString("rwxr-xr-x"));
        try (var files = Files.list(directory)) {
            for (Path file : (Iterable<Path>) files::iterator) {
                if (Files.isRegularFile(file)) {
                    Files.setPosixFilePermissions(file, PosixFilePermissions.fromString("rw-r--r--"));
                }
            }
        }
    }

    static Result docker(String... args) {
        List<String> command = new ArrayList<>();
        command.add("docker");
        command.addAll(List.of(args));
        return AgentTestSupport.run(command, Duration.ofMinutes(5));
    }

    String secret(String name) throws IOException {
        return Files.readString(secrets.resolve(name)).strip();
    }

    /** PostgreSQL container, Phase 0 and Phase 1 from the shipped files; leaves {@link #sql} connected as the superuser. */
    void startDatabaseAndMigrate(Limits postgresLimits, List<String> postgresArgs) throws IOException {
        require(docker("network", "create", network), "network");
        networkGateway = docker("network", "inspect", network, "-f", "{{(index .IPAM.Config 0).Gateway}}").output().trim();
        List<String> run = new ArrayList<>(List.of("run", "-d", "--name", db, "--network", network, "--network-alias", "db"));
        if (postgresLimits.cpus() != null) {
            run.addAll(List.of("--cpus", postgresLimits.cpus()));
        }
        if (postgresLimits.memory() != null) {
            run.addAll(List.of("--memory", postgresLimits.memory()));
        }
        run.addAll(List.of("-e", "POSTGRES_PASSWORD=" + secret("db_superuser_password"), "-e", "POSTGRES_DB=sm", "-p", "127.0.0.1::5432",
                "postgres:14"));
        run.addAll(postgresArgs);
        require(docker(run.toArray(String[]::new)), "postgres");
        RealAgentHarness.await("PostgreSQL to accept connections", Duration.ofSeconds(90),
                () -> docker("exec", db, "pg_isready", "-U", "postgres", "-d", "sm").ok());
        try {
            Thread.sleep(2500); // the image's init restart completes after the first ready
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
        }
        RealAgentHarness.await("PostgreSQL to stay ready", Duration.ofSeconds(60),
                () -> docker("exec", db, "pg_isready", "-U", "postgres", "-d", "sm").ok());
        String mapped = docker("port", db, "5432/tcp").output().lines().findFirst().orElseThrow();
        dbHostPort = Integer.parseInt(mapped.substring(mapped.lastIndexOf(':') + 1).trim());
        jdbcUrl = "jdbc:postgresql://127.0.0.1:" + dbHostPort + "/sm";
        sql = new JdbcTemplate(new DriverManagerDataSource(jdbcUrl, "postgres", secret("db_superuser_password")));

        Result phase0 = phase0();
        require(phase0, "phase 0");
        Result migrated = migrate();
        require(migrated, "phase 1");
    }

    /** Phase 0 as the shipped one-shot: the whole secrets directory read-only at /secrets, the SQL mounted from where it lives. */
    Result phase0() {
        return docker("run", "--rm", "--network", network,
                "-v", secrets + ":/secrets:ro",
                "-v", repo.resolve("runtime/bootstrap/phase0.sh") + ":/bootstrap/phase0.sh:ro",
                "-v", repo.resolve("backend/cp-core/src/main/resources/db/bootstrap/sm_control_phase0.sql") + ":/bootstrap/sm_control_phase0.sql:ro",
                "-v", repo.resolve("backend/dp-core/src/main/resources/db/bootstrap/sm_data_phase0.sql") + ":/bootstrap/sm_data_phase0.sql:ro",
                "--entrypoint", "/bin/sh", "postgres:14", "/bootstrap/phase0.sh");
    }

    /** Phase 1 as the shipped one-shot ({@code sm-migrate}): migrator roles, their passwords as files. */
    Result migrate() {
        return docker("run", "--rm", "--network", network,
                "-v", secrets.resolve("cp_migrator_password") + ":/run/secrets/cp_migrator_password:ro",
                "-v", secrets.resolve("dp_migrator_password") + ":/run/secrets/dp_migrator_password:ro",
                "-e", "SM_CONTROL_MIGRATOR_URL=jdbc:postgresql://db:5432/sm", "-e", "SM_CONTROL_MIGRATOR_USERNAME=sm_cp_migrator",
                "-e", "SM_CONTROL_MIGRATOR_PASSWORD_FILE=/run/secrets/cp_migrator_password",
                "-e", "SM_CONTROL_BOOTSTRAP_CREDENTIAL_HASH=" + new com.solace.sm.cp.identity.CredentialHasher().hash(BOOTSTRAP_SECRET.toCharArray()),
                "-e", "SM_DATA_MIGRATOR_URL=jdbc:postgresql://db:5432/sm", "-e", "SM_DATA_MIGRATOR_USERNAME=sm_dp_migrator",
                "-e", "SM_DATA_MIGRATOR_PASSWORD_FILE=/run/secrets/dp_migrator_password", "--entrypoint", "/opt/sm/bin/sm-migrate", image);
    }

    /** The documented application environment (compose.yml's names): runtime roles only, every credential a file under /run/secrets. */
    Map<String, String> launcherEnvironment(int gatewayHostPort) {
        Map<String, String> env = new LinkedHashMap<>();
        env.put("SM_CONTROL_RUNTIME_URL", "jdbc:postgresql://db:5432/sm");
        env.put("SM_CONTROL_RUNTIME_USERNAME", "sm_cp_runtime");
        env.put("SM_CONTROL_RUNTIME_PASSWORD_FILE", "/run/secrets/cp_runtime_password");
        env.put("SM_DATA_RUNTIME_URL", "jdbc:postgresql://db:5432/sm");
        env.put("SM_DATA_RUNTIME_USERNAME", "sm_dp_runtime");
        env.put("SM_DATA_RUNTIME_PASSWORD_FILE", "/run/secrets/dp_runtime_password");
        // The data plane's secret store fails closed at boot without a master key, and runtime/compose.yml supplies none (a gap found by
        // this drill, reported in the plan's Results): the drill provides one the way production reads it, from the environment (OR-85).
        env.put("SM_DP_MASTER_KEY", masterKey);
        env.put("SM_DP_MASTER_KEY_ID", "packaging-it");
        env.put("SM_GATEWAY_TRUSTED_ORIGINS_0", DeclareFixtures.CONSOLE_ORIGIN);
        // Compose's own model: the console is plain HTTP behind a TLS-terminating proxy that the console trusts by address. The host plays
        // that proxy (Docker Desktop presents the host's connections from the network's gateway address); see consoleClient().
        env.put("SM_GATEWAY_TRUSTED_PROXIES_0", networkGateway);
        env.put("SM_AGENT_GATEWAY_ENABLED", "true");
        env.put("SM_AGENT_GATEWAY_CERT", "/run/secrets/agent_gateway_cert");
        env.put("SM_AGENT_GATEWAY_KEY", "/run/secrets/agent_gateway_key");
        env.put("SM_AGENT_GATEWAY_TRUST", "/run/secrets/agent_ca_trust");
        env.put("SM_AGENT_GATEWAY_ENDPOINT", "127.0.0.1:" + gatewayHostPort);
        env.put("SM_AGENT_CA_KEYSTORE", "/run/secrets/agent_ca_keystore");
        env.put("SM_AGENT_CA_KEYSTORE_PASSWORD_FILE", "/run/secrets/agent_ca_keystore_password");
        env.put("SM_AGENT_CA_KEY_ALIAS", AgentGatewayTestPki.CA_ALIAS);
        env.put("SM_AGENT_GATEWAY_MANAGEMENT_PORT", "9445");
        env.put("SM_AGENT_GATEWAY_MANAGEMENT_BIND_ADDRESS", "0.0.0.0");
        env.put("SM_AGENT_GATEWAY_MANAGEMENT_TOKEN", MANAGEMENT_TOKEN);
        // the sweeps are off in the drills: they would race the scenarios' own rows (they have their own ITs)
        env.put("SM_AGENT_SWEEP_ENABLED", "false");
        env.put("SM_AGENT_STALENESS_JOB_ENABLED", "false");
        return env;
    }

    /** A console client that speaks as the TLS-terminating proxy would: the scheme and the caller's address in the forwarded headers. */
    static DeclareFixtures.Client consoleClient(int httpHostPort) {
        return new DeclareFixtures.Client(httpHostPort, Map.of("X-Forwarded-Proto", "https", "X-Forwarded-For", "203.0.113.7"));
    }

    /** The compose {@code secrets:} of the launcher service, as read-only bind mounts to the paths compose gives them. */
    List<String> launcherSecretMounts() {
        List<String> mounts = new ArrayList<>();
        Map<String, Path> files = new LinkedHashMap<>();
        files.put("agent_gateway_cert", certs.resolve("gateway.crt"));
        files.put("agent_gateway_key", certs.resolve("gateway.key"));
        files.put("agent_ca_trust", certs.resolve("agent-ca.pem"));
        files.put("agent_ca_keystore", certs.resolve("agent-ca.p12"));
        files.put("agent_ca_keystore_password", certs.resolve("agent-ca.password"));
        files.put("cp_runtime_password", secrets.resolve("cp_runtime_password"));
        files.put("dp_runtime_password", secrets.resolve("dp_runtime_password"));
        files.forEach((name, path) -> {
            mounts.add("-v");
            mounts.add(path + ":/run/secrets/" + name + ":ro");
        });
        return mounts;
    }

    Result startLauncher(String name, Map<String, String> env, int gatewayHostPort, int readinessHostPort, int managementHostPort,
            int httpHostPort, Limits limits) {
        List<String> args = new ArrayList<>(List.of("docker", "run", "-d", "--name", name, "--network", network));
        if (limits.cpus() != null) {
            args.addAll(List.of("--cpus", limits.cpus()));
        }
        if (limits.memory() != null) {
            args.addAll(List.of("--memory", limits.memory()));
        }
        args.addAll(List.of("-p", "127.0.0.1:" + gatewayHostPort + ":9443", "-p", "127.0.0.1:" + readinessHostPort + ":9444",
                "-p", "127.0.0.1:" + managementHostPort + ":9445", "-p", "127.0.0.1:" + httpHostPort + ":8080"));
        args.addAll(launcherSecretMounts());
        env.forEach((k, v) -> {
            args.add("-e");
            args.add(k + "=" + v);
        });
        args.add(image);
        return AgentTestSupport.run(args, Duration.ofSeconds(60));
    }

    static String health(String container) {
        return docker("inspect", "-f", "{{.State.Health.Status}}", container).output().trim();
    }

    static void awaitHealthy(String container, Duration timeout) {
        RealAgentHarness.await("container " + container + " to be healthy", timeout, () -> health(container).equals("healthy"));
    }

    private static void require(Result result, String what) {
        if (!result.ok()) {
            throw new IllegalStateException(what + " failed: " + result.output());
        }
    }

    @Override
    public void close() throws IOException {
        docker("rm", "-f", db);
        docker("network", "rm", network);
        if (ownsImage) {
            docker("image", "rm", "-f", image);
        }
        AgentTestSupport.deleteTree(work);
    }
}
